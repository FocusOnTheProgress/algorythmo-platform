/**
 * Resolve the scripted debate for a goal id. Returns a deep-ish clone so the
 * surface can mutate per-turn UI state (approved/dismissed/showing-alt)
 * without corrupting the source script.
 *
 * TODO(real-wiring): swap for a call into the director-agent debate engine.
 */
export function debateForGoal(goalId) {
  const debate = DEBATES[goalId];
  if (!debate) return null;
  return {
    goalKey: debate.goalKey,
    turns: debate.turns.map(turn => ({ ...turn })),
  };
}

