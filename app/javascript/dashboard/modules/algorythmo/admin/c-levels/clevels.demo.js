// Helper to build a ghost projection: keep the baseline up to `splitAt`, then
// bend toward `endValue` over the remaining points. Returns a 12-point series
// where indices < splitAt mirror the baseline (so the ghost diverges from now).
function project(baseline, splitAt, endValue) {
  const start = baseline[splitAt];
  const span = baseline.length - 1 - splitAt;
  return baseline.map((v, i) => {
    if (i < splitAt) return v;
    const t = span === 0 ? 1 : (i - splitAt) / span;
    // ease-in-out curve so the bend reads natural, not a straight ramp.
    const eased = t < 0.5 ? 2 * t * t : 1 - (-2 * t + 2) ** 2 / 2;
    return +(start + (endValue - start) * eased).toFixed(2);
  });
}

// Build one full projection map (indicatorId → 12-point ghost series) from a
// compact spec of { indicatorId: endValue }. `splitAt` is "now" (point 8 of
// 12 → ~3 months of projected future on the tail).
const SPLIT = 8;
function projectionFrom(spec) {
  const out = {};
  INDICATORS.forEach(ind => {
    if (spec[ind.id] === undefined) return;
    out[ind.id] = project(ind.baseline, SPLIT, spec[ind.id]);
  });
  return out;
}

